// 拼音声母列表
export const INITIALS = [
  'b', 'p', 'm', 'f', 'd', 't', 'n', 'l',
  'g', 'k', 'h', 'j', 'q', 'x',
  'zh', 'ch', 'sh', 'r', 'z', 'c', 's', 'y', 'w'
];

// 拼音韵母列表
export const FINALS = [
  'a', 'o', 'e', 'i', 'u', 'ü',
  'ai', 'ei', 'ao', 'ou',
  'an', 'en', 'ang', 'eng', 'ong',
  'ia', 'ie', 'iao', 'iou', 'ian', 'in', 'iang', 'ing', 'iong',
  'ua', 'uo', 'uai', 'uei', 'uan', 'uen', 'uang', 'ueng',
  'üe', 'üan', 'ün'
];

// 检查是否是有效的拼音组合
export function isValidPinyin(str) {
  if (!str) return false;
  str = str.toLowerCase();

  // 检查是否在词库中
  if (PINYIN_DICT[str]) return true;

  // 检查是否是有效的拼音组合
  for (const initial of INITIALS) {
    if (str.startsWith(initial)) {
      const remaining = str.slice(initial.length);
      for (const final of FINALS) {
        if (remaining === final) return true;
      }
    }
  }

  return false;
}

// 获取拼音对应的汉字
export function getCharsByPinyin(pinyin) {
  if (!pinyin) return [];
  pinyin = pinyin.toLowerCase();

  const chars = PINYIN_DICT[pinyin];
  if (chars) {
    return chars.split('');
  }

  return [];
}

// 模糊匹配拼音（支持部分输入）
export function fuzzyMatchPinyin(input) {
  if (!input) return [];
  input = input.toLowerCase();

  const results = [];

  // 精确匹配
  const exactChars = getCharsByPinyin(input);
  if (exactChars.length > 0) {
    results.push({ pinyin: input, chars: exactChars, type: 'exact' });
  }

  // 前缀匹配
  for (const pinyin in PINYIN_DICT) {
    if (pinyin.startsWith(input) && pinyin !== input) {
      results.push({ pinyin: pinyin, chars: getCharsByPinyin(pinyin), type: 'prefix' });
    }
  }

  return results;
}
